def add_tc(test_data: TestData, mode: str, binname: str, coverpoint: str, covergroup: str) -> str:
    """Register a testcase with its mode ("Sm"/"S"/"U") prefixed onto the bin name."""
    # Leading newline gives every testcase a blank separator line in the emitted asm.
    return "\n" + test_data.add_testcase(f"{mode}_{binname}", coverpoint, covergroup)


def _csr_access(instr: str, mode: str) -> str:
    """Accesses a CSR using an T-SBI or CSR operation based on mode"""
    if mode == "Sm":
        return instr
    else:
        return add_tsbi(instr)


def _load_tdata1(reg: int, trig_type: int, mode: str, lowfields: int = 0) -> list[str]:
    """Load tdata1 = (type << top) | lowfields into x{reg} and write it to tdata1."""
    lines = [
        "#if __riscv_xlen == 64",
        f"LI(x{reg}, 0x{(trig_type << 60) | lowfields:x})",
        "#else",
        f"LI(x{reg}, 0x{(trig_type << 28) | lowfields:x})",
        "#endif",
    ]
    if mode == "Sm":
        lines.append(f"csrw tdata1, x{reg} # write trigger type")
    else:
        lines.append(add_tsbi(f"csrw tdata1, x{reg} # write trigger type"))
    return lines


def _load_reg(reg: int, val: int | str) -> str:
    """Emit a load of ``val`` into x{reg}: ints via LI (constant), symbols via LA (address)."""
    return f"LA(x{reg}, {val})" if isinstance(val, str) else f"LI(x{reg}, 0x{val:x})"


def _arch_guard(instr: str, exts: list[str]) -> list[str]:
    """Bracket a single instruction with `.option arch, +ext...` (no-op if exts empty)."""
    if not exts:
        return [instr]
    adds = ", ".join(f"+{e.strip().lower()}" for e in exts)
    return [".option push", f".option arch, {adds}", instr, ".option pop"]


def ifdef_guard(instr: str, closing: bool = False) -> list[str]:
    """Emit the opening #ifdef guards for instr (or matching #endif when closing)."""
    ifdefs = INSTR_IFDEFS[instr]
    if closing:
        return ["#endif"] * len(ifdefs)
    return list(ifdefs)


def _disable_all_triggers(reg: int, mode: str) -> list[str]:
    """Disable every trigger by zeroing tdata1/2/3."""
    lines: list[str] = ["# disable all triggers"]
    if mode == "Sm":
        lines.append("csrci mstatus, 0x8 # MIE=0 while reconfiguring")
    elif mode == "S":
        lines.append("csrci sstatus, 0x2 # SIE=0 while reconfiguring")
    for t in range(UDB_NUM_TRIGGERS):
        lines.extend(
            [
                _load_reg(reg, t),
                _csr_access(f"csrw tselect, x{reg}", mode),
                _csr_access("csrw tdata1, x0", mode),
                _csr_access("csrw tdata2, x0", mode),
                _csr_access("csrw tdata3, x0", mode),
            ]
        )
    return lines


def _arm_triggers(mode: str, arm: bool) -> list[str]:
    """Set (``arm``) or clear the interrupt-enable bit that gates action=0 triggers."""
    op = "csrsi" if arm else "csrci"
    verb = "arm" if arm else "disarm"
    if mode == "Sm":
        return [f"{op} mstatus, 0x8 # MIE={int(arm)} to {verb} M-mode trigger"]
    if mode == "S":
        return [f"{op} sstatus, 0x2 # SIE={int(arm)} to {verb} S-mode trigger"]
    return []


def _config_mcontrol6(
    reg: int,
    tselect: int,
    tdata2: int | str,
    mode: str,
    *,
    privbits: int | None = None,
    xsl: int = 0b000,
    select: int = 0,
    size: int = 0,
    match: int = 0,
    chain: int = 0,
    action: int = 0,
    tdata3: int | str = 0,
) -> list[str]:
    """Emit assembly configuring trigger ``tselect`` as an mcontrol6 trigger."""
    if privbits is None:
        privbits = MODE_PRIVBIT[mode]

    m = (privbits >> 4) & 1
    s = (privbits >> 3) & 1
    u = (privbits >> 2) & 1
    vs = (privbits >> 1) & 1
    vu = privbits & 1
    lowfields = (
        (vs << 24)
        | (vu << 23)
        | (select << 21)
        | ((size & 0b111) << 16)
        | (action << 12)
        | (chain << 11)
        | ((match & 0xF) << 7)
        | (m << 6)
        | (s << 4)
        | (u << 3)
        | (xsl & 0b111)
    )
    mcontrol6 = 6  # tdata1.type
    return [
        f"# configure trigger {tselect} as mcontrol6",
        _load_reg(reg, tselect),
        _csr_access(f"csrw tselect, x{reg}", mode),
        _csr_access("csrw tdata1, x0 # disable before configuring", mode),
        _load_reg(reg, tdata2),
        _csr_access(f"csrw tdata2, x{reg} # match value", mode),
        _load_reg(reg, tdata3),
        _csr_access(f"csrw tdata3, x{reg} # textra context matching ", mode),
        f"# tdata1: type={mcontrol6} priv={privbits:05b} xsl={xsl:03b} select={select} size={size} match={match} chain={chain}",
        *_load_tdata1(reg, mcontrol6, mode, lowfields),  # load data in tdata1
    ]


def _config_icount(
    reg: int,
    tselect: int,
    count: int,
    mode: str,
    *,
    privbits: int | None = None,
    pending: int = 0,
    action: int = 0,
    tdata3: int | str = 0,
) -> list[str]:
    """Emit assembly configuring trigger ``tselect`` as an icount trigger."""
    if privbits is None:
        privbits = MODE_PRIVBIT[mode]

    m = (privbits >> 4) & 1
    s = (privbits >> 3) & 1
    u = (privbits >> 2) & 1
    vs = (privbits >> 1) & 1
    vu = privbits & 1
    lowfields = (
        (vs << 26)
        | (vu << 25)
        | ((count & 0x3FFF) << 10)
        | (m << 9)
        | (pending << 8)
        | (s << 7)
        | (u << 6)
        | (action & 0x3F)
    )
    icount = 3  # tdata1.type
    return [
        f"# configure trigger {tselect} as icount",
        *_arm_triggers(mode, False),
        _load_reg(reg, tselect),
        _csr_access(f"csrw tselect, x{reg}", mode),
        _csr_access("csrw tdata1, x0 # disable before configuring", mode),
        _load_reg(reg, tdata3),
        _csr_access(f"csrw tdata3, x{reg} # textra", mode),
        f"# tdata1: type={icount} priv={privbits:05b} count={count} pending={pending} action={action}",
        *_load_tdata1(reg, icount, mode, lowfields),  # load data in tdata1
        *_arm_triggers(mode, True),  # arm trigger
    ]


def _generate_access_tests(test_data: TestData, mode: str) -> list[TestChunk]:
    """Generate common trigger-CSR access tests."""
    covergroup = f"Sdtrig{mode}_access_cg"
    tc = test_data.begin_test_chunk("Access")
    lines = tc.code

    ######################################
    coverpoint = "cp_sdtrig_csr_access_common"
    ######################################
    lines.append(
        comment_banner(
            coverpoint,
            "Access every trigger CSR across all triggers and trigger types\n"
            "Should not cause any illegal instruction exceptions on implemented triggers",
        )
    )
    csrs = ("tdata1", "tdata2", "tdata3", "tinfo", "tcontrol", "scontext", "mcontext", "hcontext")

    type_reg, save_reg, temp_reg = test_data.int_regs.get_registers(
        3, exclude_regs=[10, 11]
    )  # exclude a0, a1 because they are used in SBI

    for trig_num in range(UDB_NUM_TRIGGERS):
        for trig_type in range(16):
            for csr in csrs:
                lines.append(f"#ifdef UDB_{csr}_AVAILABLE")
                binname = f"tselect_{trig_num}_type_{trig_type}_csr_{csr}"
                lines.extend(
                    [
                        add_tc(test_data, mode, binname, coverpoint, covergroup),
                        f"LI x{temp_reg}, {trig_num} # load trig_num value",
                        _csr_access(f"csrw tselect, x{temp_reg} # set tselect = trig_num", mode),
                        *_load_tdata1(type_reg, trig_type, mode),  # load tdata1 with the type
                        f"LI x{temp_reg}, -1 # load all 1's value",
                        _csr_access(f"csrr x{save_reg}, {csr} # save original value", mode),
                        _csr_access(f"csrw {csr}, x{temp_reg} # write all-1s", mode),
                        _csr_access(f"csrw {csr}, x0 # write all-0s", mode),
                        _csr_access(f"csrs {csr}, x{temp_reg} # set all-1s", mode),
                        _csr_access(f"csrc {csr}, x{temp_reg} # clear all-1s", mode),
                        _csr_access(f"csrw {csr}, x{save_reg} # write back original value", mode),
                    ]
                )
                lines.append("#endif")

    test_data.int_regs.return_registers([type_reg, save_reg, temp_reg])
    return [test_data.end_test_chunk()]


def _generate_native_triggers_tests(test_data: TestData, mode: str) -> list[TestChunk]:
    """Generate native trigger breakpoint-delegation tests."""
    # covergroup = "SdtrigSm_native_triggers_cg"
    tc = test_data.begin_test_chunk("NativeTriggers")
    lines: list[str] = tc.code

    lines.append("#ifdef S_SUPPORTED")
    ######################################
    coverpoint = "cp_sdtrig_breakpoint_delegate"
    ######################################
    lines.append(
        comment_banner(
            coverpoint,
            "Breakpoint from a fired trigger, taken in M-mode and delegated to\nS-mode via medeleg[3]",
        )
    )

    r1, r2, addr_reg, medeleg_reg, scr_reg = test_data.int_regs.get_registers(5)

    # TODO: sweep all triggers via CSRW(tselect, trig); using trigger 0 for now
    for delegate in (0, 1):  # medeleg[3]
        medelegop = "csrs" if delegate else "csrc"
        lines.extend(
            [
                "",
                f"# --- medeleg[3] = {delegate} ---",
                "RVTEST_GOTO_MMODE",
                f"LI(x{medeleg_reg}, 8)",  # medeleg bit 3 = breakpoint
                f"{medelegop} medeleg, x{medeleg_reg}",
            ]
        )
    lines.extend(
        [
            "",
            "# restore medeleg[3]",
            f"csrc medeleg, x{medeleg_reg}",
        ]
    )
    test_data.int_regs.return_registers([r1, r2, addr_reg, medeleg_reg, scr_reg])

    lines.append("#endif")
    return [test_data.end_test_chunk()]


