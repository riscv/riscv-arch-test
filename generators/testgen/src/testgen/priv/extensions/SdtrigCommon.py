    lines.append("#ifdef UDB_ITRIGGER_SUPPORTED")

    # one-hot tdata2 interrupt-code bins (RV64 / no-H spelling)
    intcode = ("ssi", "msi", "sti", "mti", "sei", "mei", "lcofi")

    ######################################
    coverpoint = "cp_sdtrig_itrigger"
